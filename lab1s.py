# Ввод массы в килограммах
kg = float(input("Введите массу в килограммах: "))

# Перевод килограммов в фунты
pounds = kg * 2.20462

# Перевод фунтов в унции
ounces = pounds * 16

# Перевод фунтов в стоуны
stones = pounds / 14

# Вывод результатов
print("Масса в фунтах:", round(pounds, 2))
print("Масса в унциях:", round(ounces, 2))
print("Масса в стоунах:", round(stones, 2))
